import { chromium } from "playwright";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
await page.goto("http://127.0.0.1:3001/services/search-engine-optimization/", { waitUntil: "domcontentloaded", timeout: 90000 });
const section = page.locator("section").filter({ has: page.getByRole("heading", { name: "Local search engine optimization" }) });
await section.scrollIntoViewIfNeeded();
await page.waitForTimeout(300);
const before = await page.locator("[class*='localStage']").innerText();
await page.locator("label[for='seo-market-1']").click();
await page.waitForTimeout(250);
const after = await page.locator("[class*='localStage']").innerText();
await page.locator("#seo-market-1").focus();
await page.keyboard.press("ArrowRight");
await page.waitForTimeout(200);
const arrow = await page.locator("[class*='localStage']").innerText();
await page.mouse.wheel(0, 800);
await page.waitForTimeout(200);
const height = await section.evaluate((node) => Math.round(node.getBoundingClientRect().height));
console.log("before", before.replace(/\s+/g, " ").slice(0, 110));
console.log("calgary", after.replace(/\s+/g, " ").slice(0, 110));
console.log("arrow", arrow.replace(/\s+/g, " ").slice(0, 110));
console.log("height", height);
await page.screenshot({ path: "tmp-audit/seo-local/calgary-1440.png" });
await browser.close();
