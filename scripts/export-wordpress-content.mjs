// Read-only export of WordPress page and post content into src/content/.
// Each file is the REST API response the site used to fetch at runtime, unchanged:
//   pages:    /wp-json/wp/v2/pages?slug={slug}&status=publish
//   articles: /wp-json/wp/v2/posts?slug={slug}&status=publish&_embed=1
// except that WordPress media URLs become site-relative /wp-content/ paths, served from
// public/wp-content/ (fetch new files with scripts/sync-wordpress-media.mjs).
// Then regenerates the index modules that the site imports.
//
//   node scripts/export-wordpress-content.mjs            export, then localize and index
//   node scripts/export-wordpress-content.mjs --index    localize and index the files on disk
import fs from "node:fs";
import path from "node:path";

const ORIGIN = (process.env.WORDPRESS_URL || "https://staging.kosick.com").replace(/\/+$/, "");
const ROOT = path.resolve(import.meta.dirname, "..");
const PAGES_DIR = path.join(ROOT, "src/content/pages");
const ARTICLES_DIR = path.join(ROOT, "src/content/articles");

/** WordPress pages the native routes parse (by slug). */
const PAGE_SLUGS = [
  "billboard-dimensions",
  "business-development",
  "contact",
  "corporate-branding",
  "corporate-events",
  "creative",
  "dental-marketing",
  "digital-connected-tv",
  "digital-marketing",
  "email-marketing",
  "feature-articles",
  "golf-marketing",
  "hvac-lead-generation",
  "hvac-marketing",
  "marketing-results",
  "online-payments",
  "outdoor-advertising",
  "radio-advertising",
  "search-engine-optimization",
  "services",
  "site-map",
  "social-media-marketing",
  "television-advertising",
  "thanks",
  "website-development",
];

/** Published posts the site does not serve: sources in src/lib/legacy-redirects.ts. */
const SKIPPED_POST_SLUGS = new Set(["ga4-new-generation-google-analytics"]);

/** Staging answers the odd request with a transient 5xx, so retry those. */
async function getJson(url, attempts = 4) {
  for (let attempt = 1; ; attempt += 1) {
    const response = await fetch(url, { headers: { Accept: "application/json" } });
    if (response.ok) return { data: await response.json(), headers: response.headers };
    if (response.status < 500 || attempt >= attempts) throw new Error(`${response.status} ${url}`);
    await new Promise((resolve) => setTimeout(resolve, 1000 * attempt));
  }
}

async function first(url) {
  const { data } = await getJson(url);
  if (!Array.isArray(data) || !data[0]) throw new Error(`No published item at ${url}`);
  return data[0];
}

function write(dir, slug, data) {
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, `${slug}.json`), `${JSON.stringify(data)}\n`);
}

async function listPostSlugs() {
  const slugs = [];
  for (let page = 1, total = 1; page <= total; page += 1) {
    const { data, headers } = await getJson(
      `${ORIGIN}/wp-json/wp/v2/posts?per_page=100&page=${page}&status=publish&_fields=slug`,
    );
    total = Number(headers.get("x-wp-totalpages") || "1");
    slugs.push(...data.map((post) => post.slug));
  }
  return slugs.filter((slug) => !SKIPPED_POST_SLUGS.has(slug));
}

/** WordPress-hosted media (any kosick.com host, any scheme) → the same path on this site. */
const WORDPRESS_MEDIA_HOST = /(?:https?:)?\/\/(?:staging\.|www\.)?kosick\.com(?=\/wp-content\/)/g;

function localizeFiles(dir) {
  let changed = 0;
  for (const file of fs.readdirSync(dir).filter((name) => name.endsWith(".json"))) {
    const full = path.join(dir, file);
    const before = fs.readFileSync(full, "utf8");
    const after = before.replace(WORDPRESS_MEDIA_HOST, "");
    if (after !== before) {
      fs.writeFileSync(full, after);
      changed += 1;
    }
  }
  return changed;
}

function identifier(slug, index) {
  return `${slug.replace(/[^a-z0-9]+/gi, "_").replace(/^(\d)/, "_$1")}_${index}`;
}

function writeIndex(dir, exportName, typeName, typeImport) {
  const slugs = fs
    .readdirSync(dir)
    .filter((file) => file.endsWith(".json"))
    .map((file) => file.slice(0, -".json".length))
    .sort();
  const ids = slugs.map(identifier);
  const lines = [
    "// Generated by scripts/export-wordpress-content.mjs from the JSON files in this folder. Do not edit.",
    typeImport,
    ...slugs.map((slug, i) => `import ${ids[i]} from "./${slug}.json";`),
    "",
    `export const ${exportName}: Record<string, ${typeName}> = {`,
    ...slugs.map((slug, i) => `  ${JSON.stringify(slug)}: ${ids[i]} as unknown as ${typeName},`),
    "};",
    "",
  ];
  fs.writeFileSync(path.join(dir, "index.ts"), lines.join("\n"));
  return slugs.length;
}

if (!process.argv.includes("--index")) {
  for (const slug of PAGE_SLUGS) {
    write(PAGES_DIR, slug, await first(`${ORIGIN}/wp-json/wp/v2/pages?slug=${slug}&status=publish`));
  }
  const postSlugs = await listPostSlugs();
  for (const slug of postSlugs) {
    write(
      ARTICLES_DIR,
      slug,
      await first(`${ORIGIN}/wp-json/wp/v2/posts?slug=${encodeURIComponent(slug)}&status=publish&_embed=1`),
    );
  }
  console.log(`Exported ${PAGE_SLUGS.length} pages and ${postSlugs.length} posts from ${ORIGIN}`);
}

console.log(`Localized media URLs in ${localizeFiles(PAGES_DIR) + localizeFiles(ARTICLES_DIR)} files`);

const pages = writeIndex(
  PAGES_DIR,
  "LOCAL_PAGES",
  "WordPressPage",
  'import type { WordPressPage } from "@/types/wordpress";',
);
const articles = writeIndex(
  ARTICLES_DIR,
  "LOCAL_ARTICLES",
  "LocalArticle",
  'import type { LocalArticle } from "@/lib/content/local-articles";',
);
console.log(`Indexed ${pages} pages and ${articles} articles`);
